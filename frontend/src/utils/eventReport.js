import ExcelJS from "exceljs";
import { formatClock, formatEventDate } from "./events.js";

// The attendance report of one event (SRS FR-47), as Excel or as a printable page that the
// browser can save as PDF. `report` is the answer of GET /api/event/<id>/report.

const time = (iso) =>
  iso ? new Date(iso).toLocaleTimeString([], { hour: "numeric", minute: "2-digit" }) : "—";
const stamp = (iso) =>
  new Date(iso).toLocaleString([], { year: "numeric", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" });
const programLabel = (p) => (p && p !== "ALL" ? p : "All programs");
const whenLabel = (e) =>
  `${formatEventDate(e.date)}${e.start_time ? ` · ${formatClock(e.start_time.slice(0, 5))} – ${formatClock((e.end_time || "").slice(0, 5))}` : ""}`;
const fileName = (e, ext) =>
  `oasis-report-${e.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}-${e.date}.${ext}`;

export function reportSummary(report) {
  const t = report.totals;
  return [
    ["Eligible students", t.eligible],
    ["Timed in", t.timed_in],
    ["Completed (timed out)", t.completed],
    ["Timed in only", t.timed_in_only],
    ["Absent", t.absent],
    ["Attendance rate", `${t.attendance_rate}%`],
    ["Points awarded", t.points_awarded],
  ];
}

export async function downloadReportXlsx(report) {
  const e = report.event;
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Attendance report");
  ws.columns = [
    { key: "a", width: 16 }, { key: "b", width: 32 }, { key: "c", width: 28 }, { key: "d", width: 8 },
    { key: "e", width: 12 }, { key: "f", width: 11 }, { key: "g", width: 11 }, { key: "h", width: 9 }, { key: "i", width: 15 },
  ];
  const title = ws.addRow([`${e.title} — Attendance report${report.provisional ? " (PROVISIONAL: event not closed)" : ""}`]);
  title.font = { bold: true, size: 14 };
  ws.addRow([whenLabel(e)]);
  ws.addRow([`Program: ${programLabel(e.program)} · ${e.points} points · ${e.closed_at ? `Closed ${stamp(e.closed_at)}` : "Open"}`]);
  ws.addRow([`Generated by ${report.generated_by} on ${stamp(report.generated_at)}`]).font = { italic: true, color: { argb: "FF666666" } };
  ws.addRow([]);
  reportSummary(report).forEach(([label, value]) => {
    const row = ws.addRow([label, value]);
    row.getCell(1).font = { bold: true };
  });
  ws.addRow([]);
  const header = ws.addRow(["Student Number", "Name", "Program", "Year", "Section", "Time in", "Time out", "Points", "Status"]);
  header.font = { bold: true, color: { argb: "FF2A0507" } };
  header.eachCell((c) => { c.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF2B400" } }; });
  const first = header.number;
  report.rows.forEach((r) =>
    ws.addRow([r.student_id, r.name, r.program, r.year_level, r.section, time(r.time_in), time(r.time_out), r.points, r.status])
  );
  ws.autoFilter = { from: { row: first, column: 1 }, to: { row: first, column: 9 } };
  ws.views = [{ state: "frozen", ySplit: first }];
  ws.getColumn("a").numFmt = "@";

  const blob = new Blob([await wb.xlsx.writeBuffer()], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName(e, "xlsx");
  link.click();
  URL.revokeObjectURL(url);
}

const esc = (v) => String(v ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

// Opens the report in a print-ready page; the browser's print dialog can save it as PDF.
export function printReport(report) {
  const e = report.event;
  const win = window.open("", "_blank");
  if (!win) return false;
  const summary = reportSummary(report)
    .map(([l, v]) => `<div class="tile"><b>${esc(v)}</b><span>${esc(l)}</span></div>`)
    .join("");
  const rows = report.rows
    .map((r) => `<tr><td>${esc(r.student_id)}</td><td>${esc(r.name)}</td><td>${esc(r.program)}</td><td>${esc(r.section)}</td>
      <td>${esc(time(r.time_in))}</td><td>${esc(time(r.time_out))}</td><td class="n">${esc(r.points)}</td>
      <td class="s ${r.status === "Completed" ? "ok" : r.status === "Absent" ? "no" : "mid"}">${esc(r.status)}</td></tr>`)
    .join("");
  win.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(fileName(e, "pdf"))}</title>
  <style>
    @page { size: A4; margin: 14mm; }
    body { font: 11px/1.4 Arial, sans-serif; color: #1a1a1a; margin: 0; }
    header { border-bottom: 3px solid #f2b400; padding-bottom: 8px; margin-bottom: 12px; }
    .org { color: #5a0e12; font-weight: bold; font-size: 10px; letter-spacing: .08em; text-transform: uppercase; }
    h1 { margin: 4px 0 2px; font-size: 20px; } .meta { color: #555; }
    .prov { display: inline-block; margin-top: 6px; padding: 2px 8px; border: 1px solid #b45309; color: #b45309; font-weight: bold; }
    .tiles { display: grid; grid-template-columns: repeat(7, 1fr); gap: 6px; margin: 10px 0 14px; }
    .tile { border: 1px solid #ddd; border-radius: 6px; padding: 6px; text-align: center; }
    .tile b { display: block; font-size: 16px; } .tile span { font-size: 9px; color: #555; }
    table { width: 100%; border-collapse: collapse; } th, td { border: 1px solid #ccc; padding: 4px 6px; text-align: left; }
    th { background: #f2b400; color: #2a0507; } tr:nth-child(even) td { background: #faf7f2; }
    .n { text-align: right; } .ok { color: #0f7a46; } .mid { color: #b45309; } .no { color: #b91c1c; } .s { font-weight: bold; }
    footer { margin-top: 10px; color: #777; font-size: 9px; }
  </style></head><body>
  <header>
    <div class="org">Dr. Yanga's Colleges, Inc. · College of Computer Studies · ACES · OASIS</div>
    <h1>${esc(e.title)} — Attendance report</h1>
    <div class="meta">${esc(whenLabel(e))} · ${esc(programLabel(e.program))} · ${esc(e.points)} points · ${e.closed_at ? `Closed ${esc(stamp(e.closed_at))}` : "Open"}</div>
    ${report.provisional ? '<div class="prov">PROVISIONAL — the event is not closed yet</div>' : ""}
  </header>
  <div class="tiles">${summary}</div>
  <table><thead><tr><th>Student number</th><th>Name</th><th>Program</th><th>Section</th><th>Time in</th><th>Time out</th><th>Points</th><th>Status</th></tr></thead>
  <tbody>${rows || '<tr><td colspan="8">No eligible students.</td></tr>'}</tbody></table>
  <footer>Generated by ${esc(report.generated_by)} on ${esc(stamp(report.generated_at))}. Attendance rate = completed ÷ eligible.</footer>
  <script>window.onload = () => { window.focus(); window.print(); };</script>
  </body></html>`);
  win.document.close();
  return true;
}
